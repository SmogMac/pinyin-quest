// Passive items: the main source of variety. With only one active move per hero, passives are what
// turn a run into a build. Items are unique (no duplicates) and stack freely. Each item can have:
//   stats: flat bonuses applied when the hero is built (see STAT_KEYS in combat.js), including
//          kbPct (push further) · kbRes · momentumAspd · spellPower · cdr (negative = longer
//          cooldown) · sigDur · statusDur · dodge · block
//   hooks: real gameplay triggers fired by the combat engine: (battle, payload, state) => void
//     basic attacks   onAttack {target, count, mult, extra, element, kbMult, counter, copy, forceCrit}
//                     onHit {target, dealt, crit, element, sub, counter, copy} · onCrit {target, dealt, kind}
//                     onDeal {target, dealt, kind, element, crit} (any damage you deal, not DoT)
//     defence         onDodge {src, ranged} · onBlock · onDamaged {src, dealt, kind}
//                     onHeal {amount, overflow, fruit} · onShield {amount} · onShieldBreak {absorbed, sig}
//     positioning     onKnockback {target, dist, pull} · onKnocked · onRecover · onMove
//                     onWallHit {target, speed} · onCollide {target, other, speed}
//                     onZone {enemyZone} · onMomentum {on} · while active: b.hasMomentum()
//     signature       onSignature {sig, power, choice, echo, hp, momentum} · onSignatureFail {retry}
//                     modSignature · onSigHit · onBuffEnd {id, sig} · while active: b.sigBuffActive()
//     statuses        onStatus {target, id, isNew} · onReaction {target, reaction}
//     battle          onBattleStart · onKill · onTick (1/s) · onLowHp · onFatal {prevented}
//     modifiers       modDamage modIncoming modHeal modKnockback (push you take) modKnockOut
//
// Design rules (tests/items.test.js checks them for all six heroes, one enemy, a group and a boss):
//   · every item does something real for every hero: built on shared systems (attacks, hits,
//     crits, dodges, knockback, Momentum, shields, healing, statuses, signature success), never on
//     one hero's move or one weapon type
//   · conditional items have a standalone effect that creates their condition (shield items make
//     shields, status items apply statuses, dodge items grant dodge, knockback items shove)
//   · "projectiles" from items are separate secondary projectiles, so melee heroes get them too
//   · area effects include their centre and repeat effects return to a lone target, so bosses count
//   · copied attacks (clones, mirrors, afterimages: opts.copy) carry every on-hit effect but never
//     count toward "every Nth attack" and are never copied again; items that feed themselves keep
//     short internal cooldowns (ready()), and the engine caps hook depth, procs, allies and zones
//   requires: vocabulary (any one learned Hanzi word unlocks the item for discovery)
//   category: attack | movement | dodge | defense | signature | momentum | positioning | status |
//             conditional | strange
//   tags (derived below): category, element and every trigger the item listens to.
//   Icons: src/assets/itemArt.js (generated by tools/item-art.mjs). Visuals: b.fx(kind) → FX cue
//   `item.<kind>` (FX Studio, group Items).
// Names are shown pinyin-first.
