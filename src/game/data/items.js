/** Spark Arc: an arc to another enemy, or lightning from the sky onto a lone one. */
function spark(b, target, amount) {
  const n = b.flags.arcCount || 1;
  for (let i = 0; i < n; i++) {
    const f = b.flags.arcWet ? b.foes().find((x) => x !== target && x.statuses.wet) || b.randomFoe([target]) : b.randomFoe([target]);
    if (f) arc(b, target, f, amount);
    else strike(b, target, amount * 0.75, { status: null });
  }
}
/** Ember Trail's burning ground. */
function flameZone(b, x, w, dur) {
  b.flags.flameUntil = Math.max(b.flags.flameUntil || 0, b.t + dur);
  b.addZone({ kind: 'flame', x, w, dur, hostile: true, tickEvery: 0.5, tick: (bb, u) => bb.applyStatus(u, 'burn', { dps: 3, dur: 1.5, src: bb.hero }) });
}
/** Ink Trail's ink. */
function inkZone(b, x, w, dur) {
  b.addZone({ kind: 'ink', x, w, dur, hostile: true, tickEvery: 0.5,
    tick(bb, u) {
      bb.damage(bb.hero, u, 2, { element: 'dark', kind: 'dot', noReact: true });
      bb.applyStatus(u, 'curse', { dur: 1.5, src: bb.hero });
    } });
}
/** Bursting Shield's explosion. */
function shieldBlast(b, absorbed) {
  burst(b, b.hero.x, 32, 25 + absorbed * 0.5, 'earth', { fx: 'shieldblast' });
  if (b.flags.shieldFreeze) for (const f of nearHero(b, 32)) b.applyStatus(f, 'frozen', { src: b.hero, dur: 1.5 });
}
/** Storm Guard's discharge. */
