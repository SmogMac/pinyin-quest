/** Countercurrent's gust (at most twice a second, so chained knockbacks can't loop). */
function gust(b, s, scale = 1) {
  if (!ready(b, s, 0.5, 'gust')) return;
  b.emit({ type: 'cast', spell: 'gust', element: 'wind' });
  for (const f of nearHero(b, 28)) {
    b.damage(b.hero, f, b.hero.atk * 0.25 * scale, { element: 'wind', kind: 'proc' });
    b.knockback(f, 7 * scale, { src: b.hero });
  }
}
/** A brittle shield an item grows; remembered so the item can tell when it expires unbroken. */
function growShield(b, s, amount) {
  const got = b.addShield(b.hero, amount);
  s.mine = (s.mine || 0) + got;
  s.grownAt = b.t;
  return got;
}

