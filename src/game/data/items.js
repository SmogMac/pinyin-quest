/** Borrowed Time: a frozen afterimage that repeats the last attack a second later. */
function afterimageOf(b) {
  const loop = b.flags.timeLoop;
  const a = clone(b, { ttl: loop ? 1.9 : 1.3, interval: 99, dmg: 0, x: b.hero.x, frozen: true });
  if (!a) return;
  for (const d of loop ? [1, 1.6] : [1]) {
    b.schedule(d, () => {
      if (b.result || !a.alive) return;
      b.heroAttack({ copy: true, from: a.id, mult: 1 });
    });
  }
}
/** Trickster's Mask: trade places with the nearest enemy. */
function trickSwap(b, s) {
  if (b.t - (s.at ?? -9) < 4) return;
  const f = b.front();
  if (!f) return;
  s.at = b.t;
  const H = b.hero;
  const hx = H.x;
  b.fx('swap', { tgt: 'hero', src: f });
  H.x = Math.min(b.worldW - 6, f.x);
  f.x = Math.max(2, hx);
  f.px = f.x;
  H.px = H.x;
  b.applyStatus(f, 'stun', { dur: 0.8, src: H });
  s.crit = true;
  b.label(H, 'miàn jù!', 'good');
  b.trigger('onMove', { x: H.x });
}

